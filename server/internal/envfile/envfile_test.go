package envfile_test

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/Paul-Carouge/Alcove/server/internal/envfile"
)

func TestTake(t *testing.T) {
	path, rest := envfile.Take([]string{"alcove", "serve", "--env-file=/etc/a.env", "--http=:80"})
	if path != "/etc/a.env" || !reflect.DeepEqual(rest, []string{"alcove", "serve", "--http=:80"}) {
		t.Fatalf("%q %v", path, rest)
	}
	path, rest = envfile.Take([]string{"alcove", "--env-file", "x.env", "serve"})
	if path != "x.env" || !reflect.DeepEqual(rest, []string{"alcove", "serve"}) {
		t.Fatalf("%q %v", path, rest)
	}
}

func TestWriteThenLoad(t *testing.T) {
	p := filepath.Join(t.TempDir(), "alcove.env")
	if err := envfile.Write(p, "generated by tests", [][2]string{{"ALCOVE_T_A", `va"lue`}, {"ALCOVE_T_B", "b"}}); err != nil {
		t.Fatal(err)
	}
	if info, _ := os.Stat(p); info.Mode().Perm() != 0o600 {
		t.Errorf("mode = %v", info.Mode().Perm())
	}
	t.Setenv("ALCOVE_T_B", "from-env")
	if err := envfile.Load(p); err != nil {
		t.Fatal(err)
	}
	if got := os.Getenv("ALCOVE_T_A"); got != `va"lue` {
		t.Errorf("A = %q", got)
	}
	if os.Getenv("ALCOVE_T_B") != "from-env" {
		t.Error("existing environment must win")
	}
	_ = os.Unsetenv("ALCOVE_T_A")
}

func TestLoadRejectsGarbage(t *testing.T) {
	p := filepath.Join(t.TempDir(), "bad.env")
	_ = os.WriteFile(p, []byte("# ok\nNOT A LINE\n"), 0o600)
	if err := envfile.Load(p); err == nil {
		t.Fatal("expected an error")
	}
}
